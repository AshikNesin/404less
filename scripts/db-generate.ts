#!/usr/bin/env tsx
/**
 * `pnpm db:generate [drizzle-kit args]`: run drizzle-kit generate, then refresh
 * apps/web/drizzle/index.ts so the Workers entry can import every migration
 * and apply it at boot (Node applies them straight from the folder).
 */
import { spawnSync } from "node:child_process";
import { readdirSync, writeFileSync } from "node:fs";

const OUT_DIR = "apps/web/drizzle";

const result = spawnSync("pnpm", ["exec", "drizzle-kit", "generate", ...process.argv.slice(2)], {
  stdio: "inherit",
  shell: process.platform === "win32",
});
if (result.status !== 0) process.exit(result.status ?? 1);

const files = readdirSync(OUT_DIR)
  .filter((file) => file.endsWith(".sql"))
  .sort();

const lines = [
  "// Generated by `pnpm db:generate` from the .sql files in this folder. Do not edit.",
  "// The Workers entry applies these on first request; Node uses drizzle's migrator directly.",
  ...files.map((file, index) => `import m${index} from "./${file}";`),
  "",
  "export const migrations = [",
  ...files.map((file, index) => `  { name: ${JSON.stringify(file)}, sql: m${index} },`),
  "];",
  "",
];
writeFileSync(`${OUT_DIR}/index.ts`, lines.join("\n"));
// Format like the pre-commit hook would, so CI's drift check sees no diff.
spawnSync("pnpm", ["exec", "vp", "fmt", `${OUT_DIR}/index.ts`], {
  stdio: "ignore",
  shell: process.platform === "win32",
});
console.log(`✓ ${OUT_DIR}/index.ts lists ${files.length} migration(s)`);
